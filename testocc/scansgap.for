c-----scansg-----------------------------------------------------------
c
      program scansg
c
c     extracts the pairing gap and shell gap
c     from out put on 'for002' as generated by the routine 'hffit'
c     using the standard set on 'for010.gap'.
c
      parameter (kmaxsv=100)
      character*100 a
      character*8   akey
c
c----------------------------------------------------------------------
c
      open(19,form='formatted',status='scratch')
      write(6,'(10x,a)')
     &  ' S_2p^-   S_2p^+  shellg_2  shellg_4     gap_58 '
      iset   = 0
      isetmx = 0
      do 10 iread=1,9999
      read(5,'(a)',err=999,end=999) a
      if(a(22:28).eq.'comment') then
        iset  = 1 + iset
        akey  = a(30:37)
        do 20 ir2=1,999
        read(5,'(a)',err=999,end=999) a
c
c        collect all energy related observables
c
        if(a(4:10).eq.'binding') then
          read(5,*) ia,in,dummy,enerm2
          read(5,*) ia,in,dummy,enerm1
          read(5,*) ia,in,dummy,energ0
          read(5,*) ia,in,dummy,enerp1
          read(5,*) ia,in,dummy,enerp2
          s2ppzr = (enerp2-energ0)/2.0
          s2pmzr = (energ0-enerm2)/2.0
          delold = s2ppzr-s2pmzr
          delgap = -0.125*(enerp2-4*enerp1+6*energ0-4*enerm1+enerm2)
c
c        collect %error in R and sigma
c
        elseif(a(4:13).eq.'gap-proton') then
          read(5,*) ia,in,dummy,delg1
          read(5,*) ia,in,dummy,delg2
          read(5,*) ia,in,dummy,delg3
c
c        everything is collected now --> print
c
          write(6,'(1x,a,4f8.2,5x,f8.2)')
     &      akey,s2pmzr,s2ppzr,delold,delgap,delg3
          goto 29
        endif
   20   continue
   29   continue
      endif
   10 continue
  999 continue
c
      end



