# --- 2) Interpolation helper (linear on a Delaunay triangulation) ---

def interpolate_to_regular_grid(points_xy, values, x_min=None, x_max=None, y_min=None, y_max=None,
                                nx=200, ny=200):
    """
    Interpolate scattered or gridded (x,y)->z data onto a regular mesh using
    matplotlib.tri.LinearTriInterpolator (piecewise-linear on the triangulation).

    Returns Xi, Yi, Zi (masked array).
    """
    x = points_xy[:, 0]
    y = points_xy[:, 1]

    if x_min is None: x_min = np.min(x)
    if x_max is None: x_max = np.max(x)
    if y_min is None: y_min = np.min(y)
    if y_max is None: y_max = np.max(y)

    # Regular target grid
    xi = np.linspace(x_min, x_max, nx)
    yi = np.linspace(y_min, y_max, ny)
    Xi, Yi = np.meshgrid(xi, yi)

    # Triangulate + linear interpolator
    tri = mtri.Triangulation(x, y)
    lin_interp = mtri.LinearTriInterpolator(tri, values)

    Zi = lin_interp(Xi, Yi)  # masked array; masked outside convex hull

    return Xi, Yi, Zi

